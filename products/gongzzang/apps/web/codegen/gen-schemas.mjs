// Generates the web's zod schemas from the foundation's schema registry (root ADR-0336): for each
// registered subject the web consumes, the subject's current revision narrowed to the paths the
// web's pact in the registry says it reads, written where that pact names (`consumers[].at`).
// `pnpm gen:schemas` writes them; `lib/api/schema-registry.test.ts` holds the committed files to
// this output, so a registry change that alters what the web parses is regenerated in the same PR.
// A revision that adds a field the web does not read regenerates nothing.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const REPOSITORY = resolve(dirname(fileURLToPath(import.meta.url)), "../../../../..");
const REGISTRY = "platforms/foundation-platform/contracts/schema-registry";
const CONSUMER = "web";

function pascal(name) {
  return name.replace(/(^|_)([a-z])/g, (_, __, letter) => letter.toUpperCase());
}

function types(node) {
  return node.type === undefined ? [] : [node.type].flat();
}

/// The zod expression of `node` at `path`, keeping the members `reads` reaches.
function zodOf(node, path, reads, indent) {
  const kinds = types(node).filter((kind) => kind !== "null");
  if (kinds.length !== 1) {
    throw new Error(`${path || "<root>"}: one type besides null, not ${types(node)}`);
  }
  const [kind] = kinds;
  if (node.enum !== undefined && !node["x-open-enum"]) {
    return `z.enum([${node.enum.map((value) => JSON.stringify(value)).join(", ")}])`;
  }
  switch (kind) {
    case "string":
      return node.pattern === undefined ? "z.string()" : `z.string().regex(/${node.pattern}/)`;
    case "integer":
      return "z.number().int()";
    case "number":
      return "z.number()";
    case "boolean":
      return "z.boolean()";
    case "array":
      return `z.array(${zodOf(node.items, `${path}[]`, reads, indent)})`;
    case "object": {
      const inner = `${indent}  `;
      const members = [];
      for (const [name, member] of Object.entries(node.properties ?? {})) {
        const at = path === "" ? name : `${path}.${name}`;
        const reached = (read) =>
          read === at || read.startsWith(`${at}.`) || read.startsWith(`${at}[]`);
        if (!reads.some(reached)) continue;
        const required = (node.required ?? []).includes(name);
        const nullable = types(member).includes("null");
        const suffix = !required ? ".nullish()" : nullable ? ".nullable()" : "";
        members.push(`${inner}${name}: ${zodOf(member, at, reads, inner)}${suffix},`);
      }
      return `z.object({\n${members.join("\n")}\n${indent}})`;
    }
    default:
      throw new Error(`${path || "<root>"}: type ${kind} is outside what the generator writes`);
  }
}

/// Every generated file: its path from the repository root and its text.
export function generate(repository = REPOSITORY) {
  const registry = JSON.parse(readFileSync(resolve(repository, REGISTRY, "registry.json"), "utf8"));
  const files = [];
  for (const entry of registry.subjects) {
    for (const consumer of entry.consumers.filter((c) => c.name === CONSUMER)) {
      const current = entry.revisions.filter((r) => r.major === entry.major).at(-1);
      const short = entry.subject.replace(/^foundation-platform\./, "");
      const file = `${short}/${current.major}/${current.revision}.schema.json`;
      const schema = JSON.parse(readFileSync(resolve(repository, REGISTRY, file), "utf8"));
      const reads = consumer.reads.map((read) => read.path);
      const name = pascal(short);
      files.push({
        path: consumer.at,
        text: [
          `// Generated by apps/web/codegen/gen-schemas.mjs from ${REGISTRY} (root ADR-0336):`,
          `// ${entry.subject} major ${entry.major}, its current revision narrowed to the paths the web's`,
          "// pact reads (any revision of the major reads the same). Do not edit; change the registry and",
          "// run `pnpm gen:schemas`.",
          'import { z } from "zod";',
          "",
          `export const ${name}Subject = ${JSON.stringify(entry.subject)};`,
          `export const ${name}Major = ${entry.major};`,
          "",
          `export const ${name}Schema = ${zodOf(schema, "", reads, "")};`,
          "",
        ].join("\n"),
      });
    }
  }
  return files;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const file of generate()) {
    writeFileSync(resolve(REPOSITORY, file.path), file.text);
    console.log(`wrote ${file.path}`);
  }
}
